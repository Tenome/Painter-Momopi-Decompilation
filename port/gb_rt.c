#include "gb_rt.h"
#include "apu.h"
#include "texture.h"
#include "levelpack.h"

Regs r;
int ime;
uint64_t cycles;
uint8_t gb_joy;
uint8_t gb_framebuf[GB_MAX_W * 144];
int gb_margin;                      /* extra pixels shown on each side of the 160 pixel screen in play (widescreen option) */
int gb_view_w = 160;                /* width of the rendered picture: 160 + 2 * gb_margin */
int gb_sprite_limit_off;             /* option: sprites are also kept in a long list that the renderer uses (no 40 sprite limit) */
uint8_t gb_xoam[GB_XOAM * 4], gb_xoam_shown[GB_XOAM * 4];
int gb_xoam_n, gb_xoam_shown_n;
int gb_wide_active;                 /* set by the game logic while the play screen is shown */
void (*gb_frame_hook)(unsigned frame);
void (*gb_audio_hook)(const int16_t *stereo, int frames);
unsigned gb_frames;
unsigned gb_spin;
int gb_trace;

static const uint8_t *rom;
static size_t rom_size;
static unsigned bank = 1;
static uint8_t vram[0x2000], wram[0x2000], oam[0xA0], hram[0x80], io[0x80], ie;

/* generated by tools/recomp.py */
typedef struct { uint16_t addr; uint8_t bank; fn_t fn; } Entry;
extern const Entry gb_entries[];
extern const int gb_nentries;
extern fn_t gb_vectors[5];

void gb_fatal(const char *why, unsigned v) {
    fprintf(stderr, "recompiled game: %s %04x (bank %u, pc cycles %llu)\n", why, v, bank, (unsigned long long)cycles);
    exit(2);
}

void gb_load_rom(const uint8_t *data, size_t size) { rom = data; rom_size = size; }

void gb_reset_state(void) {
    memset(&r, 0, sizeof r);
    r.a = 0x01; r.f = 0xB0; r.c = 0x13; r.e = 0xD8; r.h = 0x01; r.l = 0x4D; r.sp = 0xFFFE;
    memset(io, 0, sizeof io);
    io[0x40] = 0x91; io[0x47] = 0xFC; io[0] = 0xCF;
    apu_reset();
    ime = 0; ie = 0; cycles = 0; bank = 1; gb_frames = 0;
}

void gb_trace_fn(fn_t f) {
    for (int i = 0; i < gb_nentries; i++)
        if (gb_entries[i].fn == f) {
            if (gb_trace == 4) { if (gb_entries[i].addr == 0x45D1 && gb_entries[i].bank == 1) fprintf(stderr, "%02x %04x %04x\n", r.a, BC(), DE()); return; }
            fprintf(stderr, "[f%u] %u:%04X\n", gb_frames, gb_entries[i].bank, gb_entries[i].addr);
            return;
        }
}

fn_t gb_dispatch(uint16_t addr) {
    for (int i = 0; i < gb_nentries; i++)
        if (gb_entries[i].addr == addr && (addr < 0x4000 || gb_entries[i].bank == bank)) return gb_entries[i].fn;
    fprintf(stderr, "regs: A=%02x BC=%04x DE=%04x HL=%04x SP=%04x\n", r.a, BC(), DE(), HL(), r.sp);
    if (BC() >= 0xC000 && BC() < 0xDFE0) { fprintf(stderr, "record @%04x:", BC()); for (int i = 0; i < 0x20; i++) fprintf(stderr, " %02x", rd(BC() + i)); fprintf(stderr, "\n"); }
    gb_fatal("indirect jump to unknown routine", addr);
    return 0;
}


uint8_t rd(uint16_t a) {
    if (a < 0x4000) return rom[a];
    if (gb_pack_view && a < 0x8000) return gb_pack_win[a - 0x4000];     /* the spawn data of a level pack */
    if (a < 0x8000) { size_t o = (size_t)(bank % (rom_size / 0x4000)) * 0x4000 + a - 0x4000; return rom[o]; }
    if (a < 0xA000) return vram[a - 0x8000];
    if (a < 0xC000) return 0xFF;
    if (a < 0xE000) return wram[a - 0xC000];
    if (a < 0xFE00) return wram[a - 0xE000];
    if (a < 0xFEA0) return oam[a - 0xFE00];
    if (a < 0xFF00) return 0xFF;
    if (a < 0xFF80) {
        unsigned x = a - 0xFF00;
        if (x == 0) {
            uint8_t v = 0xCF;
            if (!(io[0] & 0x10)) v &= ~(gb_joy & 0x0F);
            if (!(io[0] & 0x20)) v &= ~((gb_joy >> 4) & 0x0F);
            return v;
        }
        if (x == 0x0F) return io[0x0F] | 0xE0;
        if (x >= 0x10 && x < 0x40) return apu_read(a, io[x]);
        return io[x];
    }
    if (a < 0xFFFF) return hram[a - 0xFF80];
    return ie;
}

int gb_watch = -1;                 /* main_headless --watch ADDR: print the frame and value of every write there */
void wr(uint16_t a, uint8_t v) {
    if (a == gb_watch) fprintf(stderr, "write %04x = %02x (frame %u)\n", a, v, gb_frames);
    if (a < 0x8000) { if (a >= 0x2000 && a < 0x4000) bank = (v & 0x1F) ? (v & 0x1F) : 1; return; }
    if (a < 0xA000) vram[a - 0x8000] = v;
    else if (a < 0xC000) {}
    else if (a < 0xE000) wram[a - 0xC000] = v;
    else if (a < 0xFE00) wram[a - 0xE000] = v;
    else if (a < 0xFEA0) oam[a - 0xFE00] = v;
    else if (a < 0xFF00) {}
    else if (a < 0xFF80) {
        unsigned x = a - 0xFF00;
        if (x == 0x46) { unsigned s = v << 8; for (int i = 0; i < 0xA0; i++) oam[i] = rd(s + i); memcpy(gb_xoam_shown, gb_xoam, (size_t)gb_xoam_n * 4); gb_xoam_shown_n = gb_xoam_n; }
        else if (x == 0x00) io[0] = v & 0x30;
        else if (x == 0x44) {}
        else { io[x] = v; if (x >= 0x10 && x < 0x40) apu_write(a, v); }
    }
    else if (a < 0xFFFF) hram[a - 0xFF80] = v;
    else ie = v;
}

/* the HRAM routine copied by CopyOamDmaRoutine: ld a,$c0; ldh [rDMA],a; ld a,$28; dec a; jr nz; ret */
void gb_dma_routine(void) {
    wr(0xFF46, 0xC0);
    r.a = 0; r.f = (r.f & 0x10) | 0xC0;
    CYC(4 + 12 + 4 + 0x28 * 16 - 4 + 16);
}

/* ---- texture pack support: tiles with a full-colour replacement are remembered per pixel (which texture, which source pixel, which palette) while the
 * Game Boy picture is built; a second pass then writes the colour picture (gb_color_scale times larger) ---- */
uint32_t gb_colorbuf[GB_MAX_W * 8 * 144 * 8];
uint32_t gb_color_pal[4] = {0x00FFFFFF, 0x00AAAAAA, 0x00555555, 0x00000000};
int gb_color_scale = 1;
static uint32_t refbuf[GB_MAX_W * 144];                 /* (VRAM tile number + 1) << 16 (tmap gives its texture) | palette << 12 | y << 4 | x ; 0 = none */
static int tmap[384];

static uint32_t blend(uint32_t base, uint32_t over, unsigned a) {
    unsigned r1 = (base >> 16) & 255, g1 = (base >> 8) & 255, b1 = base & 255, r2 = (over >> 16) & 255, g2 = (over >> 8) & 255, b2 = over & 255;
    return ((r1 * (255 - a) + r2 * a) / 255) << 16 | ((g1 * (255 - a) + g2 * a) / 255) << 8 | ((b1 * (255 - a) + b2 * a) / 255);
}

static void color_pass(int W, unsigned bgp, unsigned obp0, unsigned obp1) {
    const int S = gb_color_scale;
    const int CW = W * S;
    for (int y = 0; y < 144; y++) for (int x = 0; x < W; x++) {
        uint32_t ref = refbuf[y * W + x];
        uint32_t flat = gb_color_pal[gb_framebuf[y * W + x] & 3];
        if (!ref) {
            for (int sy = 0; sy < S; sy++) for (int sx = 0; sx < S; sx++) gb_colorbuf[(y * S + sy) * CW + x * S + sx] = flat;
            continue;
        }
        const GbTex *t = gb_texture_get(tmap[(ref >> 16) - 1]);
        unsigned pal = (ref >> 12) & 15, lx = ref & 15, ly = (ref >> 4) & 15;
        unsigned p = pal == 0 ? bgp : pal == 1 ? obp0 : obp1;
        unsigned fade = (3 - ((p >> 6) & 3)) * 255 / 3;                      /* the fade steps of the Game Boy palettes lighten the picture */
        int n = t->scale, ts = 8 * n;
        for (int sy = 0; sy < S; sy++) for (int sx = 0; sx < S; sx++) {
            int tx = (int)lx * n + sx * n / S, ty = (int)ly * n + sy * n / S;
            const uint8_t *q = t->rgba + ((size_t)ty * ts + tx) * 4;
            uint32_t c = (uint32_t)q[0] << 16 | q[1] << 8 | q[2];
            if (q[3] < 255) c = blend(gb_color_pal[0], c, q[3]);
            if (fade) c = blend(c, 0x00FFFFFF, fade);
            gb_colorbuf[(y * S + sy) * CW + x * S + sx] = c;
        }
    }
}

static void render(void) {
    unsigned lcdc = io[0x40];
    static uint8_t bgcol[GB_MAX_W * 144];
    const int W = gb_view_w, M = (W - 160) / 2, wide = gb_wide_active && M > 0;
    const int tex_on = gb_tex_count > 0;
    memset(bgcol, 0, sizeof bgcol);
    memset(gb_framebuf, 0, sizeof gb_framebuf);
    if (tex_on) {
        memset(refbuf, 0, sizeof refbuf);
        for (int t = 0; t < 384; t++) tmap[t] = gb_texture_find(vram + t * 16);
        gb_color_scale = gb_tex_scale;
    } else gb_color_scale = 1;
    if (!(lcdc & 0x80)) { if (tex_on) color_pass(W, io[0x47], io[0x48], io[0x49]); return; }
    unsigned bgp = io[0x47], pal[4];
    for (int i = 0; i < 4; i++) pal[i] = (bgp >> (2 * i)) & 3;
    unsigned scx = io[0x43], scy = io[0x42], mapbase = (lcdc & 8) ? 0x1C00 : 0x1800;
    int sgn = !(lcdc & 0x10);
    if (lcdc & 1) {
        for (int y = 0; y < 144; y++) for (int x = 0; x < W; x++) {
            int sx = x - M;
            if (sx < 0 || sx >= 160) {                    /* the margins: the room only, nothing wrapped around */
                int wx2 = (int)scx + sx;
                if (!wide || wx2 < 0 || wx2 > 255) { gb_framebuf[y * W + x] = pal[0]; continue; }
            }
            unsigned yy = (y + scy) & 255, xx = (unsigned)((int)scx + sx) & 255;
            unsigned t = vram[mapbase + (yy >> 3) * 32 + (xx >> 3)];
            unsigned base = sgn ? 0x1000 + (int8_t)t * 16 : t * 16;
            unsigned lo = vram[base + (yy & 7) * 2], hi = vram[base + (yy & 7) * 2 + 1], bit = 7 - (xx & 7);
            unsigned ci = ((hi >> bit) & 1) << 1 | ((lo >> bit) & 1);
            bgcol[y * W + x] = ci; gb_framebuf[y * W + x] = pal[ci];
            if (tex_on && tmap[base >> 4] >= 0) refbuf[y * W + x] = (uint32_t)((base >> 4) + 1) << 16 | (yy & 7) << 4 | (xx & 7);
        }
    }
    if (lcdc & 0x20) {
        int wy = io[0x4A], wx = (int)io[0x4B] - 7;
        unsigned wmap = (lcdc & 0x40) ? 0x1C00 : 0x1800;
        for (int y = wy < 0 ? 0 : wy; y < 144; y++) for (int sx = wx < 0 ? 0 : wx; sx < 160; sx++) {
            int yy = y - wy, xx = sx - wx, x = sx + M;
            unsigned t = vram[wmap + (yy >> 3) * 32 + (xx >> 3)];
            unsigned base = sgn ? 0x1000 + (int8_t)t * 16 : t * 16;
            unsigned lo = vram[base + (yy & 7) * 2], hi = vram[base + (yy & 7) * 2 + 1], bit = 7 - (xx & 7);
            unsigned ci = ((hi >> bit) & 1) << 1 | ((lo >> bit) & 1);
            bgcol[y * W + x] = ci; gb_framebuf[y * W + x] = pal[ci];
            refbuf[y * W + x] = (tex_on && tmap[base >> 4] >= 0) ? (uint32_t)((base >> 4) + 1) << 16 | (yy & 7) << 4 | (xx & 7) : 0;
        }
    }
    if (lcdc & 2) {
        int h = (lcdc & 4) ? 16 : 8;
        const uint8_t *src = oam;
        int count = 40;
        if (gb_sprite_limit_off && gb_xoam_shown_n) { src = gb_xoam_shown; count = gb_xoam_shown_n; }
        for (int i = count - 1; i >= 0; i--) {
            int sy = src[i * 4] - 16, sx = src[i * 4 + 1] - 8 + (wide ? 0 : M);   /* widescreen: the game logic wrote output coordinates */
            unsigned tile = src[i * 4 + 2], fl = src[i * 4 + 3];
            unsigned palid = (fl & 0x10) ? 2 : 1;
            unsigned p = (fl & 0x10) ? io[0x49] : io[0x48], sp[4];
            for (int k = 0; k < 4; k++) sp[k] = (p >> (2 * k)) & 3;
            if (h == 16) tile &= 0xFE;
            for (int yy = 0; yy < h; yy++) {
                int y = sy + yy;
                if (y < 0 || y >= 144) continue;
                int row = (fl & 0x40) ? h - 1 - yy : yy;
                unsigned base = tile * 16 + row * 2, lo = vram[base], hi = vram[base + 1];
                const GbTex *tx = (tex_on && h == 8 && tmap[tile] >= 0) ? gb_texture_get(tmap[tile]) : 0;
                for (int xx = 0; xx < 8; xx++) {
                    int x = sx + xx;
                    if (x < 0 || x >= W) continue;
                    unsigned bit = (fl & 0x20) ? xx : 7 - xx;
                    unsigned ci = ((hi >> bit) & 1) << 1 | ((lo >> bit) & 1);
                    unsigned lx = 7 - bit;                                       /* source pixel column of the tile */
                    if (tx) {
                        uint64_t m = 1ull << (row * 8 + (int)lx);
                        if (!((ci != 0 || (tx->edited & m)) && !(tx->clear & m))) continue;
                    } else if (!ci) continue;
                    if ((fl & 0x80) && bgcol[y * W + x]) continue;
                    gb_framebuf[y * W + x] = sp[ci];
                    refbuf[y * W + x] = tx ? (uint32_t)(tile + 1) << 16 | palid << 12 | (unsigned)row << 4 | lx : 0;
                }
            }
        }
    }
    if (tex_on) color_pass(W, io[0x47], io[0x48], io[0x49]);
}

void gb_host_vblank(void) {
    gb_spin = 0;
    io[0x0F] |= 0x01;
    render();
    gb_frames++;
    cycles += 70224;
    if (gb_audio_hook) { static int16_t buf[2 * 800]; apu_mix(buf, 735); gb_audio_hook(buf, 735); }
    if (gb_frame_hook) gb_frame_hook(gb_frames);
    if (ime && (ie & 1)) {                 /* the VBlank interrupt, delivered between frames */
        io[0x0F] &= ~1;
        Regs saved = r;
        ime = 0;
        r.sp -= 2;
        if (gb_vectors[0]) gb_run(gb_vectors[0]);
        r = saved;
        ime = 1;
    }
}

void gb_service(void) {}

/* FNV-1a hash of the work RAM, high RAM, video RAM and OAM: used to compare two builds frame by frame (main_headless --hashes). */
uint32_t gb_state_hash(void) {
    static int skip_spawn_ptr = -1;
    if (skip_spawn_ptr < 0) skip_spawn_ptr = getenv("GB_HASH_SKIP") != 0;
    uint32_t h = 2166136261u;
    for (unsigned i = 0; i < 0x1000; i++) {
        if (skip_spawn_ptr && (i == 0x481 || i == 0x482)) continue;      /* the spawn list pointer points into the pack's own data (GB_HASH_SKIP=1) */
        h = (h ^ wram[i]) * 16777619u;
    }     /* $d000 and up is only the stack (residue below SP differs between equal routines) */
    for (unsigned i = 0; i < sizeof hram; i++) h = (h ^ hram[i]) * 16777619u;
    for (unsigned i = 0; i < sizeof vram; i++) h = (h ^ vram[i]) * 16777619u;
    for (unsigned i = 0; i < sizeof oam; i++) h = (h ^ oam[i]) * 16777619u;
    for (unsigned i = 0; i < sizeof io; i++) h = (h ^ io[i]) * 16777619u;     /* sound and video registers */
    return h;
}

/* Write work RAM, high RAM, video RAM and OAM (in that order) to a file: used to find what differs between two builds (main_headless --dump). */
void gb_dump_state(const char *path) {
    FILE *f = fopen(path, "wb");
    if (!f) return;
    fwrite(wram, 1, sizeof wram, f);
    fwrite(hram, 1, sizeof hram, f);
    fwrite(vram, 1, sizeof vram, f);
    fwrite(oam, 1, sizeof oam, f);
    fwrite(io, 1, sizeof io, f);
    fclose(f);
}
