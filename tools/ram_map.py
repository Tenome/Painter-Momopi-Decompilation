#!/usr/bin/env python3
"""Write docs/RAM_MAP.md: named RAM variables (src/constants.inc) and the most used addresses that still have no name.

    python tools/ram_map.py
"""
import collections, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
consts = {}
comments = {}
for ln in open(os.path.join(ROOT, "src", "constants.inc"), encoding="utf-8"):
    m = re.match(r"\s*DEF\s+(\w+)\s+EQU\s+\$([0-9a-fA-F]+)\s*(?:;\s*(.*))?", ln)
    if m and int(m[2], 16) >= 0xC000:
        consts[m[1]] = int(m[2], 16)
        comments[m[1]] = m[3] or ""
text = "\n".join(open(os.path.join(ROOT, "src", f"bank_{b:02x}.asm"), encoding="utf-8").read() for b in range(4))
use = collections.Counter()
for name in consts:
    use[name] = len(re.findall(r"\b" + re.escape(name) + r"\b", text))
raw = collections.Counter(int(a, 16) for a in re.findall(r"\$([cdf][0-9a-f]{3})\b", text) if int(a, 16) not in consts.values())
out = ["# RAM map (generated by tools/ram_map.py)", "",
       "Named variables come from `src/constants.inc`; the counts are references in `src/bank_*.asm`.", "",
       "| Address | Name | References | Meaning |", "|---|---|---|---|"]
for name, a in sorted(consts.items(), key=lambda x: x[1]):
    out.append(f"| ${a:04x} | `{name}` | {use[name]} | {comments[name]} |")
out += ["", "## Most used addresses without a name", "", "| Address | References |", "|---|---|"]
for a, n in raw.most_common(40):
    out.append(f"| ${a:04x} | {n} |")
open(os.path.join(ROOT, "docs", "RAM_MAP.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(consts), "named,", len(raw), "unnamed addresses referenced")
