#!/usr/bin/env python3
"""Write docs/CALLGRAPH.md: for every routine in config/functions.tsv, its callees (from src/bank_NN.asm)."""
import os, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
funcs = [ln.rstrip("\n").split("\t") for ln in list(open(os.path.join(ROOT, "config", "functions.tsv")))[1:]]
order = {}
src = {}
for b in range(4):
    p = os.path.join(ROOT, "src", f"bank_{b:02x}.asm")
    if os.path.exists(p):
        src[b] = open(p, encoding="utf-8").read().splitlines()
callees = collections.defaultdict(set)
callers = collections.defaultdict(set)
cur = None
names = {f[3] for f in funcs}
for b, lines in src.items():
    for ln in lines:
        m = re.match(r"^(\w+)::?", ln)
        if m:
            cur = m[1] if m[1] in names else cur
            continue
        m = re.match(r"\s+(?:call|jp)(?: \w+,)? ([A-Za-z_]\w+)", ln)
        if m and cur and m[1] in names and m[1] != cur:
            callees[cur].add(m[1])
            callers[m[1]].add(cur)
out = ["# Call graph (generated by tools/callgraph.py)", "",
       "Routines with a name other than `L_BB_AAAA` are listed first. `calls` are direct `call`/`jp` targets.", ""]
named = [f for f in funcs if not f[3].startswith("L_")]
out.append(f"{len(named)} named routines of {len(funcs)} found.\n")
out.append("| Bank:Addr | Name | Size | Called by | Calls |")
out.append("|---|---|---|---|---|")
for b, a, sz, nm in named:
    out.append(f"| {b}:{a} | `{nm}` | {sz} | {len(callers[nm])} | {', '.join('`'+c+'`' for c in sorted(callees[nm])[:8])}{' ...' if len(callees[nm]) > 8 else ''} |")
open(os.path.join(ROOT, "docs", "CALLGRAPH.md"), "w", newline="\n", encoding="utf-8").write("\n".join(out) + "\n")
print(len(named), "named of", len(funcs))
