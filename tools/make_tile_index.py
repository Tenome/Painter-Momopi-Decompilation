#!/usr/bin/env python3
"""Write build/recomp/tile_index.c: the tile sheets of gfx.csv (name, number of tiles, the 16 bytes of every tile) for the texture pack loader.

The native player replaces tiles by content: a texture sheet PNG (same name as assets/gfx/<bank>_<addr>_<name>.png, any whole-number size multiple of the
128 pixel wide sheet) is compared tile by tile with the original tile data listed here; the tiles that differ become full-colour replacements.
"""
import csv, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(out=None):
    out = out or os.path.join(ROOT, "build", "recomp", "tile_index.c")
    sheets = []
    with open(os.path.join(ROOT, "gfx.csv"), encoding="utf-8") as f:
        for r in csv.reader(l for l in f if l.strip() and not l.startswith("#")):
            if r[0] == "bank":
                continue
            bank, addr, name = int(r[0]), r[1], r[2]
            path = os.path.join(ROOT, "assets", f"bank_{bank:02x}", f"{addr}_{name}.bin")
            if not os.path.exists(path):
                continue
            sheets.append((f"{bank}_{addr}_{name}", open(path, "rb").read()))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("/* generated by tools/make_tile_index.py */\n#include <stdint.h>\n#include \"texture.h\"\n")
        for i, (name, data) in enumerate(sheets):
            f.write(f"static const uint8_t sheet{i}[] = {{" + ",".join(str(b) for b in data) + "};\n")
        f.write("const GbSheet gb_sheets[] = {\n")
        for i, (name, data) in enumerate(sheets):
            f.write(f'    {{"{name}", {len(data) // 16}, sheet{i}}},\n')
        f.write("};\n")
        f.write(f"const int gb_nsheets = {len(sheets)};\n")
    print(f"{len(sheets)} sheets -> {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
